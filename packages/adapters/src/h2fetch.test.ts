import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync } from 'node:fs';
import http2 from 'node:http2';
import https from 'node:https';
import type { AddressInfo } from 'node:net';
import { tmpdir } from 'node:os';
import path from 'node:path';
import zlib from 'node:zlib';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createH2Fetch } from './h2fetch';
import { extractListings } from './extract';
import { RequestLayer } from './request';

const fixture = readFileSync(
  path.join(__dirname, '..', 'snapshots', 'olx-live-2026-10.html'),
  'utf8',
);
const BLOCK =
  '<HTML><HEAD><TITLE>ERROR: The request could not be satisfied</TITLE></HEAD><BODY><H1>403 ERROR</H1>Request blocked. Generated by cloudfront (CloudFront)</BODY></HTML>';

function hasOpenssl() {
  try {
    execFileSync('openssl', ['version'], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

// A stand-in for OLX's CloudFront: HTTP/1.1 clients get "403 Request blocked", HTTP/2 clients get the page.
describe.skipIf(!hasOpenssl())('HTTP/2 fetch against a CloudFront-like server', () => {
  let server: http2.Http2SecureServer;
  let origin = '';
  let cert = '';
  const open = new Set<http2.ServerHttp2Session>();

  beforeAll(async () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'h2-'));
    execFileSync(
      'openssl',
      [
        'req',
        '-x509',
        '-newkey',
        'rsa:2048',
        '-nodes',
        '-days',
        '1',
        '-subj',
        '/CN=localhost',
        '-addext',
        'subjectAltName=DNS:localhost,IP:127.0.0.1',
        '-keyout',
        path.join(dir, 'key.pem'),
        '-out',
        path.join(dir, 'cert.pem'),
      ],
      { stdio: 'ignore' },
    );
    cert = readFileSync(path.join(dir, 'cert.pem'), 'utf8');
    server = http2.createSecureServer(
      { key: readFileSync(path.join(dir, 'key.pem')), cert, allowHTTP1: true },
      (req, res) => {
        if (req.httpVersion !== '2.0') {
          res.writeHead(403, { 'content-type': 'text/html' });
          res.end(BLOCK);
          return;
        }
        if (req.url === '/uk/list/q-notebook/?page=1') {
          res.writeHead(301, { location: '/uk/list/q-notebook/' });
          res.end();
          return;
        }
        res.writeHead(200, {
          'content-type': 'text/html; charset=utf-8',
          'content-encoding': 'gzip',
        });
        res.end(zlib.gzipSync(fixture));
      },
    );
    server.on('session', (session) => open.add(session));
    await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
    origin = `https://localhost:${(server.address() as AddressInfo).port}`;
  });

  afterAll(async () => {
    for (const session of open) session.destroy();
    await new Promise<void>((resolve) => server?.close(() => resolve()));
  });

  it('gets the page over HTTP/2 (following redirects, gunzipping) where HTTP/1.1 is blocked', async () => {
    const h2 = createH2Fetch({ ca: cert });
    const response = await h2(`${origin}/uk/list/q-notebook/?page=1`, {
      headers: { 'user-agent': 'test' },
    });
    expect(response.status).toBe(200);
    expect(response.url).toBe(`${origin}/uk/list/q-notebook/`);
    const items = extractListings(await response.text(), { baseUrl: 'https://www.olx.ua/' });
    expect(items).toHaveLength(4);
  });

  it('RequestLayer with the HTTP/2 fetch returns listings instead of pausing the site', async () => {
    const layer = new RequestLayer({
      fetchImpl: createH2Fetch({ ca: cert }),
      sleep: async () => undefined,
    });
    const result = await layer.getText(
      { id: 'olx', maxConcurrency: 1, minDelayMs: 0 },
      `${origin}/uk/list/q-notebook/?page=1`,
    );
    expect(result.status).toBe(200);
    expect(extractListings(result.text, { baseUrl: 'https://www.olx.ua/' }).length).toBe(4);
  });

  it('an HTTP/1.1 client gets the CloudFront block (the bug this fixes)', async () => {
    const response = await new Promise<{ status: number; body: string }>((resolve, reject) => {
      https
        .get(`${origin}/uk/list/q-notebook/`, { ca: cert }, (res) => {
          let body = '';
          res.on('data', (chunk) => (body += chunk));
          res.on('end', () => resolve({ status: res.statusCode ?? 0, body }));
        })
        .on('error', reject);
    });
    expect(response.status).toBe(403);
    expect(response.body).toContain('Request blocked');
  });
});
