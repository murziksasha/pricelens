import { h2fetch } from './h2fetch';

export interface SiteBudget {
  id: string;
  maxConcurrency: number;
  minDelayMs: number;
  pausedUntil?: number | null;
}

export interface FetchTextResult {
  status: number;
  text: string;
  url: string;
}

export class SitePausedError extends Error {
  readonly code = 'site_paused';
  constructor(readonly siteId: string) {
    super('site_paused');
  }
}

export class UpstreamError extends Error {
  readonly code = 'upstream_error';
  constructor(
    readonly status: number,
    message = 'upstream_error',
  ) {
    super(message);
  }
}

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36 PriceLens';

/** True for CDN/anti-bot block pages (CloudFront "Request blocked", captcha walls) served with any status. */
export function looksBlockedPage(text: string): boolean {
  return /request blocked|generated by cloudfront|cf-browser-verification|cf-challenge|cf_chl_opt|<title>\s*just a moment|challenge_passed=|g-recaptcha|hcaptcha/i.test(
    text,
  );
}

/**
 * A challenge marker on a full 2xx shop page is usually a login-form captcha widget, not a wall
 * (click.ua ships g-recaptcha on every page). Only short 2xx pages count as a challenge.
 */
const FULL_PAGE_BYTES = 60_000;

function isBlocked(status: number, text: string): boolean {
  if (status === 429 || status === 503) return true;
  if (status === 403 && /captcha|cloudflare|cloudfront|access denied|request blocked|just a moment/i.test(text)) return true;
  if (status < 300 && text.length >= FULL_PAGE_BYTES) return false;
  if (/g-recaptcha|hcaptcha|cf-challenge|cf-browser-verification|cf_chl_opt/i.test(text)) return true;
  return false;
}

/** Pages a shop serves when its own search backend hiccups; worth asking again (ek.ua). */
export function looksTransientError(text: string): boolean {
  return text.length < 200_000 && /Произошел сбой при выполнении поиска|Стався збій під час пошуку/i.test(text);
}

/**
 * Some shops (Horoshop, e.g. proton-it.kyiv.ua) answer with a tiny script that busy-waits and then
 * sets a fixed cookie. Returns that cookie so the request can be repeated with it.
 */
export function jsCookieChallenge(text: string): string | null {
  if (text.length > 4000) return null;
  const hash = /defaultHash\s*=\s*["']([0-9a-f]{16,128})["']/i.exec(text);
  const name = /document\.cookie\s*=\s*["']([A-Za-z0-9_]+)=["']\s*\+\s*defaultHash/.exec(text);
  return hash && name ? `${name[1]}=${hash[1]}` : null;
}

export interface ProxyHook {
  decorate(url: string, init: RequestInit): Promise<{ url: string; init: RequestInit }>;
}

/** Per-site rate limit, concurrency, jitter, and backoff. Proxy is a hook only (FR-SCH-006). */
export class RequestLayer {
  private running = new Map<string, number>();
  private waiters = new Map<string, Array<() => void>>();
  private nextAt = new Map<string, number>();
  private paused = new Map<string, number>();
  private cookies = new Map<string, string>();

  constructor(
    private opts: {
      fetchImpl?: typeof fetch;
      sleep?: (ms: number) => Promise<void>;
      now?: () => number;
      random?: () => number;
      proxy?: ProxyHook;
      onPause?: (siteId: string, reason: string) => void | Promise<void>;
      timeoutMs?: number;
      /** Called for the first URL and every redirect hop; throw to refuse (SSRF guard). */
      urlGuard?: (url: string) => Promise<void>;
    } = {},
  ) {}

  private now() {
    return this.opts.now ? this.opts.now() : Date.now();
  }

  private async sleep(ms: number) {
    if (this.opts.sleep) return this.opts.sleep(ms);
    await new Promise((resolve) => setTimeout(resolve, ms));
  }

  private async enter(site: SiteBudget) {
    const pausedUntil = Math.max(site.pausedUntil ?? 0, this.paused.get(site.id) ?? 0);
    if (pausedUntil > this.now()) throw new SitePausedError(site.id);
    while ((this.running.get(site.id) ?? 0) >= site.maxConcurrency) {
      await new Promise<void>((resolve) => {
        const queue = this.waiters.get(site.id) ?? [];
        queue.push(resolve);
        this.waiters.set(site.id, queue);
      });
    }
    this.running.set(site.id, (this.running.get(site.id) ?? 0) + 1);
    const jitter = 0.7 + (this.opts.random ? this.opts.random() : Math.random()) * 0.6;
    const delay = site.minDelayMs * jitter;
    const wait = Math.max(0, (this.nextAt.get(site.id) ?? 0) - this.now());
    if (wait > 0) await this.sleep(wait);
    this.nextAt.set(site.id, this.now() + delay);
  }

  private leave(siteId: string) {
    this.running.set(siteId, Math.max(0, (this.running.get(siteId) ?? 1) - 1));
    const queue = this.waiters.get(siteId);
    const next = queue?.shift();
    if (next) next();
  }

  async getText(site: SiteBudget, url: string): Promise<FetchTextResult> {
    await this.enter(site);
    try {
      let attempt = 0;
      let transientRetries = 0;
      while (true) {
        const headers: Record<string, string> = {
          'user-agent': UA,
          // A browser-like Accept: ek.ua answers "search failed" without application/xhtml+xml.
          accept: 'text/html,application/xhtml+xml,application/xml;q=0.9,application/json;q=0.8,*/*;q=0.7',
          'accept-language': 'uk-UA,uk;q=0.9,ru;q=0.8,en;q=0.7',
        };
        const cookie = this.cookies.get(new URL(url).host);
        if (cookie) headers.cookie = cookie;
        const guard = this.opts.urlGuard;
        const fetchImpl = this.opts.fetchImpl ?? h2fetch;
        const controller = new AbortController();
        const timeoutMs = this.opts.timeoutMs ?? 20_000;
        const timer = setTimeout(() => controller.abort(), timeoutMs);
        let target = url;
        let response!: Response;
        let text: string;
        try {
          // With a guard, redirects are followed by hand so every hop is checked (at most 5).
          let hop = url;
          for (let redirects = 0; ; redirects += 1) {
            if (guard) await guard(hop);
            target = hop;
            let init: RequestInit = { headers, redirect: guard ? 'manual' : 'follow' };
            if (this.opts.proxy) {
              const decorated = await this.opts.proxy.decorate(target, init);
              target = decorated.url;
              init = decorated.init;
            }
            response = await fetchImpl(target, { ...init, signal: controller.signal });
            const location = response.headers.get('location');
            if (!guard || response.status < 300 || response.status >= 400 || !location) break;
            if (redirects >= 5) throw new UpstreamError(response.status, 'too_many_redirects');
            await response.body?.cancel().catch(() => undefined);
            hop = new URL(location, hop).toString();
          }
          text = await response.text();
        } catch (err: unknown) {
          if (controller.signal.aborted || (err as { name?: string })?.name === 'AbortError') {
            throw new Error('timeout');
          }
          throw err;
        } finally {
          clearTimeout(timer);
        }
        const challengeCookie = jsCookieChallenge(text);
        if (challengeCookie && challengeCookie !== cookie) {
          this.cookies.set(new URL(url).host, challengeCookie);
          attempt += 1;
          if (attempt < 3) continue;
        }
        if (looksTransientError(text) && transientRetries < 3) {
          transientRetries += 1;
          await this.sleep(1500 * transientRetries);
          continue;
        }
        if (looksTransientError(text)) throw new UpstreamError(response.status, 'upstream_search_failed');
        if (isBlocked(response.status, text)) {
          attempt += 1;
          if (attempt >= 3) {
            const until = this.now() + 15 * 60_000;
            this.paused.set(site.id, until);
            await this.opts.onPause?.(site.id, 'captcha_or_rate_limit');
            throw new SitePausedError(site.id);
          }
          await this.sleep(1000 * 2 ** (attempt - 1));
          continue;
        }
        if (response.status >= 500) throw new UpstreamError(response.status);
        return { status: response.status, text, url: target };
      }
    } finally {
      this.leave(site.id);
    }
  }
}
